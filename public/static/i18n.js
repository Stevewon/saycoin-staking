function createLangSelector(containerId) {
  const container = document.getElementById(containerId);
  if (!container) return;

  const langs = [
    { code: 'ko', label: '\ud55c\uad6d\uc5b4', flag: '\ud83c\uddf0\ud83c\uddf7' },
    { code: 'en', label: 'English', flag: '\ud83c\uddfa\ud83c\uddf8' },
    { code: 'ja', label: '\u65e5\u672c\u8a9e', flag: '\ud83c\uddef\ud83c\uddf5' },
    { code: 'zh', label: '\u4e2d\u6587', flag: '\ud83c\udde8\ud83c\uddf3' },
    { code: 'vi', label: 'Ti\u1ebfng Vi\u1ec7t', flag: '\ud83c\uddfb\ud83c\uddf3' },
    { code: 'th', label: '\u0e44\u0e17\u0e22', flag: '\ud83c\uddf9\ud83c\udded' }
  ];

  const current = langs.find(l => l.code === I18N.getLang()) || langs[0];

  container.innerHTML = `
    <div class="relative inline-block" id="langDropdownWrapper">
      <button onclick="toggleLangDropdown()" class="flex items-center gap-1 px-2 py-1 sm:px-3 sm:py-2 bg-white border border-gray-300 rounded-lg hover:bg-gray-50 transition text-sm" id="langDropdownBtn">
        <span>${current.flag}</span>
        <span class="hidden sm:inline text-xs">${current.label}</span>
        <i class="fas fa-chevron-down text-xs text-gray-400 ml-1"></i>
      </button>
      <div id="langDropdown" class="hidden absolute right-0 top-full mt-1 bg-white border border-gray-200 rounded-lg shadow-lg z-50 min-w-[140px]">
        ${langs.map(l => `
          <button onclick="selectLang('${l.code}')" class="w-full flex items-center gap-2 px-3 py-2 hover:bg-purple-50 text-sm ${l.code === current.code ? 'bg-purple-100 text-purple-700 font-bold' : 'text-gray-700'}">
            <span>${l.flag}</span>
            <span>${l.label}</span>
          </button>
        `).join('')}
      </div>
    </div>
  `;
}

function toggleLangDropdown() {
  const dd = document.getElementById('langDropdown');
  dd.classList.toggle('hidden');
  // Close on outside click
  setTimeout(() => {
    document.addEventListener('click', closeLangDropdown);
  }, 10);
}

function closeLangDropdown(e) {
  const wrapper = document.getElementById('langDropdownWrapper');
  if (wrapper && !wrapper.contains(e.target)) {
    document.getElementById('langDropdown').classList.add('hidden');
    document.removeEventListener('click', closeLangDropdown);
  }
}

function selectLang(code) {
  I18N.setLang(code);
  document.getElementById('langDropdown').classList.add('hidden');
  // Refresh lang selector display
  const container = document.getElementById('langSelector');
  if (container) createLangSelector('langSelector');
  // Some pages need full reload for dynamic content
  if (typeof onLanguageChange === 'function') {
    onLanguageChange(code);
  }
}

