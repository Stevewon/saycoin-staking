const I18N = {
  _currentLang: 'ko',
  _translations: {},
  _isKoreaIP: false,

  // Get current language
  getLang() {
    return this._currentLang;
  },

  // Check if user is from Korea
  isKoreaIP() {
    return this._isKoreaIP;
  },

  // Set language and apply
  setLang(lang) {
    // 한국 IP에서는 한국어 외 변경 불가
    if (this._isKoreaIP) lang = 'ko';
    if (!this._translations[lang]) lang = 'ko';
    this._currentLang = lang;
    localStorage.setItem('quantarium_lang', lang);
    document.documentElement.lang = lang;
    this.applyAll();
  },

  // ★ Country(ISO-3166 alpha2) -> Language code 매핑
  //   사장님 정책 (2026-05-10): IP 기준 각 나라 언어로 자동 표시
  //   - KR: 무조건 한국어 (사용자 변경 불가, 기존 정책 유지)
  //   - JP: 일본어 / CN·HK·TW·MO·SG: 중국어 / VN: 베트남어 / TH: 태국어
  //   - 그 외 모든 국가: 영어
  _countryToLang(country) {
    if (!country) return null;
    const c = country.toUpperCase();
    if (c === 'KR') return 'ko';
    if (c === 'JP') return 'ja';
    if (c === 'CN' || c === 'HK' || c === 'TW' || c === 'MO' || c === 'SG') return 'zh';
    if (c === 'VN') return 'vi';
    if (c === 'TH') return 'th';
    return 'en';
  },

  // Initialize
  init() {
    // 서버에서 전달한 국가 정보 확인 (Cloudflare CF-IPCountry 헤더 기반)
    const countryMeta = document.querySelector('meta[name="user-country"]');
    const userCountry = countryMeta ? countryMeta.getAttribute('content').toUpperCase() : '';
    this._isKoreaIP = (userCountry === 'KR');

    if (this._isKoreaIP) {
      // 한국 IP: 무조건 한국어, localStorage도 강제 (기존 정책 유지)
      this._currentLang = 'ko';
      localStorage.setItem('quantarium_lang', 'ko');
    } else {
      // 한국 외 IP: 우선순위 → 사용자 수동 선택(localStorage) > IP 국가 > 브라우저 언어 > 영어
      const saved = localStorage.getItem('quantarium_lang');
      if (saved && this._translations[saved]) {
        this._currentLang = saved;
      } else {
        // ★ 1순위: IP 국가 기반 자동 매핑 (사장님 신규 정책 2026-05-10)
        const ipLang = this._countryToLang(userCountry);
        if (ipLang && this._translations[ipLang]) {
          this._currentLang = ipLang;
        } else {
          // 2순위 fallback: 브라우저 언어
          const browserLang = (navigator.language || navigator.userLanguage || 'en').substring(0, 2);
          this._currentLang = this._translations[browserLang] ? browserLang : 'en';
        }
      }
    }
    document.documentElement.lang = this._currentLang;
    this.applyAll();
  },

  // Get translation by key
  t(key) {
    const lang = this._currentLang;
    const dict = this._translations[lang] || this._translations['ko'];
    return dict[key] || this._translations['ko'][key] || key;
  },

  // Apply translations to all elements with data-i18n attribute
  applyAll() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const text = this.t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.placeholder = text;
      } else if (el.tagName === 'OPTION') {
        el.textContent = text;
      } else {
        el.textContent = text;
      }
    });
    // Apply placeholder translations
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = this.t(el.getAttribute('data-i18n-placeholder'));
    });
    // Apply title translations
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      el.title = this.t(el.getAttribute('data-i18n-title'));
    });
    // Apply innerHTML translations (for elements with icons)
    document.querySelectorAll('[data-i18n-html]').forEach(el => {
      const key = el.getAttribute('data-i18n-html');
      const tpl = el.getAttribute('data-i18n-tpl') || '';
      if (tpl) {
        el.innerHTML = tpl.replace('{{text}}', this.t(key));
      }
    });
  }
};

// ============================================
// Language Selector Component
// ============================================
function createLangSelector(containerId) {
  const container = document.getElementById(containerId);
  if (!container) return;

  // 한국 IP에서는 언어 선택기 완전히 숨김
  if (I18N.isKoreaIP()) {
    container.innerHTML = '';
    container.style.display = 'none';
    return;
  }

  const langs = [
    { code: 'ko', label: '\ud55c\uad6d\uc5b4', flag: '\ud83c\uddf0\ud83c\uddf7' },
    { code: 'en', label: 'English', flag: '\ud83c\uddfa\ud83c\uddf8' },
    { code: 'ja', label: '\u65e5\u672c\u8a9e', flag: '\ud83c\uddef\ud83c\uddf5' },
    { code: 'zh', label: '\u4e2d\u6587', flag: '\ud83c\udde8\ud83c\uddf3' },
    { code: 'vi', label: 'Ti\u1ebfng Vi\u1ec7t', flag: '\ud83c\uddfb\ud83c\uddf3' },
    { code: 'th', label: '\u0e44\u0e17\u0e22', flag: '\ud83c\uddf9\ud83c\udded' }
  ];

  const current = langs.find(l => l.code === I18N.getLang()) || langs[0];

  container.innerHTML = `
    <div class="relative inline-block" id="langDropdownWrapper">
      <button onclick="toggleLangDropdown()" class="flex items-center gap-1 px-2 py-1 sm:px-3 sm:py-2 bg-white border border-gray-300 rounded-lg hover:bg-gray-50 transition text-sm" id="langDropdownBtn">
        <span>${current.flag}</span>
        <span class="hidden sm:inline text-xs">${current.label}</span>
        <i class="fas fa-chevron-down text-xs text-gray-400 ml-1"></i>
      </button>
      <div id="langDropdown" class="hidden absolute right-0 top-full mt-1 bg-white border border-gray-200 rounded-lg shadow-lg z-50 min-w-[140px]">
        ${langs.map(l => `
          <button onclick="selectLang('${l.code}')" class="w-full flex items-center gap-2 px-3 py-2 hover:bg-purple-50 text-sm ${l.code === current.code ? 'bg-purple-100 text-purple-700 font-bold' : 'text-gray-700'}">
            <span>${l.flag}</span>
            <span>${l.label}</span>
          </button>
        `).join('')}
      </div>
    </div>
  `;
}

function toggleLangDropdown() {
  const dd = document.getElementById('langDropdown');
  dd.classList.toggle('hidden');
  // Close on outside click
  setTimeout(() => {
    document.addEventListener('click', closeLangDropdown);
  }, 10);
}

function closeLangDropdown(e) {
  const wrapper = document.getElementById('langDropdownWrapper');
  if (wrapper && !wrapper.contains(e.target)) {
    document.getElementById('langDropdown').classList.add('hidden');
    document.removeEventListener('click', closeLangDropdown);
  }
}

function selectLang(code) {
  I18N.setLang(code);
  document.getElementById('langDropdown').classList.add('hidden');
  // Refresh lang selector display
  const container = document.getElementById('langSelector');
  if (container) createLangSelector('langSelector');
  // Some pages need full reload for dynamic content
  if (typeof onLanguageChange === 'function') {
    onLanguageChange(code);
  }
}

